#!/usr/bin/env node
// T-704(ADR-010 §3.4 CF-1、docs/security/findings.md SB-9/SB-10/SB-11対応):
// 演習実行Worker(harness.worker.ts/sqlHarness.worker.ts/sqlSchemaHarness.worker.ts)に
// allowlist方式(CSP)で通信そのものを遮断する。
//
// なぜ`_headers`をビルド後生成にしているか: Next.js(webpack)は`new Worker(new URL(...))`を
// 内容ハッシュ付きファイル名の静的チャンク(例: `3464.e6c109effd9e5da5.js`)として出力し、
// このハッシュはビルドのたびに変わる(依存グラフの変化でチャンクID自体も動きうる)。
// OpenNext Cloudflareの静的アセット配信はWorkerスクリプト(`.open-next/worker.js`)を
// 経由しない(`assets`バインディングが直接返す)ため、`next.config.js`の`headers()`は
// これらのファイルに効かない(Cloudflare公式ドキュメント: "Custom headers defined in the
// `_headers` file are not applied to responses generated by your Worker code"の逆で、
// `_headers`は静的アセット配信にのみ効く)。そのため実際に生成されたファイル名を
// ビルド後にスキャンして特定し、`_headers`へ書き出す(ファイル名のハードコード不可)。
//
// マーカー文字列でチャンクを識別する理由: 各Workerのエントリはビルド時にトップレベル
// entryとして扱われ(`new Worker(url)`経由でのみ参照され、他モジュールからimportされない)、
// exportされた関数名はterserによって自由にmangleされうる。一方コード中の文字列リテラル
// (エラーメッセージ等)はminifyされても変化しない。各Workerに一意な文字列を選定した
// (harness.worker.tsの禁止トークンエラー文言、sqlHarness.worker.ts=sqlCompare.ts由来の
// 列不一致エラー文言、sqlSchemaHarness.worker.ts=PRAGMA table_info呼び出し)。
//
// 該当チャンクが見つからない/複数該当した場合は、CLAUDE.md絶対規則3
// (モック・スタブでの誤魔化し禁止)に従いビルドを失敗させる(サイレントスキップ禁止)。
// マーカー解決(resolveWorkerChunkFile)とヘッダー本文組み立て(buildHeadersOutput)は
// 副作用のない純粋関数として切り出してあり、tests/unit/scripts/generateWorkerCspHeaders.test.ts
// からファイルI/Oなしで検証できる。

import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * 各Workerサンドボックスに適用するCSP。default-src 'none'を起点に、
 * そのWorkerの正当な動作に必要な最小限のみを明示的に許可する
 * (allowlist方式、findings.mdの結論: denylist方式は構造的に不十分)。
 */
export const WORKER_TARGETS = [
  {
    name: "harness.worker.ts (JSサンドボックス実行Worker、T-107a)",
    // checkForbiddenTokens()のエラー文言(harness.worker.ts)。
    marker: "禁止された構文が含まれています",
    // 通信をallowlistで原則禁止(connect-src 'none')。ユーザーコードのロードは
    // Blob URL経由のESM動的import(loadModuleFromCode)のみが正当な経路のため
    // script-srcに'self'(このWorker自身のスクリプト)と'blob:'を許可する。
    // 'blob:'はWorker自身のスクリプトソースとしては使わないが、ユーザーコードの
    // import(blob:...)先として必要(script-srcは動的importの読み込み先も規律する)。
    // findings.md SB-9(import()のブロックコメント難読化)はscript-srcが'self'/'blob:'
    // 以外の起点を許可しないことで、静的検出をすり抜けてもネットワークに到達できない。
    csp: "default-src 'none'; script-src 'self' blob:; connect-src 'none'; worker-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'",
  },
  {
    name: "sqlHarness.worker.ts (SQL採点Worker、T-201)",
    // sqlCompare.tsの列不一致エラー文言(sqlHarness.worker.tsのみがimportする)。
    marker: "列が一致しません",
    // sql.js(SQLite WASM)は同一オリジンの/generated/*.wasmをfetchする必要があるため
    // connect-src 'self'(外部ホストへの通信は依然として禁止)。WebAssembly.instantiate
    // には'wasm-unsafe-eval'が必要(script-srcに'unsafe-eval'は含めない)。
    csp: "default-src 'none'; script-src 'self' 'wasm-unsafe-eval'; connect-src 'self'; worker-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'",
  },
  {
    name: "sqlSchemaHarness.worker.ts (スキーマビューアWorker、T-202)",
    // PRAGMA table_info呼び出しの静的部分(sqlSchemaHarness.worker.tsのみ)。
    marker: "PRAGMA table_info(",
    csp: "default-src 'none'; script-src 'self' 'wasm-unsafe-eval'; connect-src 'self'; worker-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'",
  },
];

/**
 * `target.marker`を含むファイルをちょうど1件に一意特定する。0件/複数件は
 * サイレントに握りつぶさずthrowする(呼び出し側でビルド失敗として扱う)。
 * @param {{name: string, marker: string}} target
 * @param {string[]} chunkFiles
 * @param {(file: string) => string} readFile
 */
export function resolveWorkerChunkFile(target, chunkFiles, readFile) {
  const matches = chunkFiles.filter((file) => readFile(file).includes(target.marker));

  if (matches.length === 0) {
    throw new Error(
      `${target.name} に対応するチャンクが見つかりません(マーカー文字列 "${target.marker}" ` +
        `を含むファイルが存在しない)。ソースが変更されマーカーが変わった可能性がある。` +
        `このスクリプトのWORKER_TARGETSを更新すること` +
        `(サイレントにCSP未適用のまま進めることは禁止)。`,
    );
  }
  if (matches.length > 1) {
    throw new Error(
      `${target.name} のマーカー文字列 "${target.marker}" が複数ファイルにマッチした` +
        `(${matches.join(", ")})。一意に識別できないため停止する。`,
    );
  }
  return matches[0];
}

/** `_headers`の1ブロック(パス+ヘッダ行)を組み立てる。 */
export function buildHeaderBlock(file, csp) {
  return `/_next/static/chunks/${file}\n  Content-Security-Policy: ${csp}`;
}

/** 既存の`_headers`内容(あれば)に新規ブロックを追記した最終出力を組み立てる。 */
export function buildHeadersOutput(existingContent, blocks) {
  const existing = existingContent.trimEnd();
  const generated = blocks.join("\n\n");
  return existing ? `${existing}\n\n${generated}\n` : `${generated}\n`;
}

function main() {
  const rootDir = fileURLToPath(new URL("..", import.meta.url));
  const assetsDir = path.join(rootDir, ".open-next", "assets");
  const chunksDir = path.join(assetsDir, "_next", "static", "chunks");
  const headersPath = path.join(assetsDir, "_headers");

  if (!existsSync(chunksDir)) {
    console.error(
      `チャンクディレクトリが見つかりません: ${chunksDir}\n` +
        `このスクリプトは "opennextjs-cloudflare build" の後に実行する必要があります。`,
    );
    process.exit(1);
  }

  const chunkFiles = readdirSync(chunksDir).filter((f) => f.endsWith(".js"));
  const readFile = (file) => readFileSync(path.join(chunksDir, file), "utf-8");

  const blocks = [];
  for (const target of WORKER_TARGETS) {
    let file;
    try {
      file = resolveWorkerChunkFile(target, chunkFiles, readFile);
    } catch (e) {
      console.error(`[generate-worker-csp-headers] ${e instanceof Error ? e.message : String(e)}`);
      process.exit(1);
    }
    blocks.push(buildHeaderBlock(file, target.csp));
    console.log(`[generate-worker-csp-headers] ${target.name} -> /_next/static/chunks/${file}`);
  }

  const existing = existsSync(headersPath) ? readFileSync(headersPath, "utf-8") : "";
  writeFileSync(headersPath, buildHeadersOutput(existing, blocks));
  console.log(`[generate-worker-csp-headers] 書き込み完了: ${headersPath}`);
}

const isMainModule = process.argv[1] && import.meta.url === `file://${process.argv[1]}`;
if (isMainModule) {
  main();
}
